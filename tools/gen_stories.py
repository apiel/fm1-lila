"""gen_stories.py OUT.h: the stories (assets/stories/*.txt and the .lpc made from them by tools/story_make.py) as C, for synth.c.

The texts become the captions (ASCII: the screen's font has no accents) and each line's scene code: the world drawn behind it
(Lila's story: a world index; Goldilocks: a room), + 0x80 when the scene's characters are there too."""
import struct
import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
STORIES = ["lila_fr", "goldilocks_en"]          # story 0, 1: the presets' `story` field
SCENES = {"lila_fr": "BIRD COW DOG FROG SPACE METEOR BLOCKS DINO ROBOT OCEAN CASTLE JUNGLE".split(),
          "goldilocks_en": "FOREST HOUSE KITCHEN CHAIRS BEDROOM".split()}


def ascii_of(s):
    s = s.replace("œ", "oe").replace("Œ", "OE").replace("’", "'").replace("«", '"').replace("»", '"').replace("…", "...")
    s = unicodedata.normalize("NFKD", s)
    return "".join(c for c in s if 32 <= ord(c) < 127)


def cstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main(out):
    lines = ["/* generated by tools/gen_stories.py */", "#pragma once", "#include <stdint.h>", f"#define NSTORY {len(STORIES)}", ""]
    table = []
    for si, name in enumerate(STORIES):
        txt = ROOT / "assets" / "stories" / f"{name}.txt"
        lpc = txt.with_suffix(".lpc")
        parts = []
        for ln in txt.read_text(encoding="utf-8").splitlines():
            if ln.strip() and not ln.startswith("#"):
                sc, t = ln.split("|", 1)
                code = SCENES[name].index(sc.strip().rstrip("*")) | (0x80 if sc.strip().endswith("*") else 0)
                parts.append((code, ascii_of(t.strip())))
        raw = lpc.read_bytes() if lpc.exists() else b"LPC1" + struct.pack("<H", 0)
        if raw[:4] != b"LPC1":
            raise SystemExit(f"{lpc}: not an LPC1 file")
        n = struct.unpack("<H", raw[4:6])[0]
        offs, cnts = [], []
        for i in range(n):
            o, c = struct.unpack("<IH", raw[6 + 6 * i:12 + 6 * i])
            offs.append(o)
            cnts.append(c)
        frames = raw[6 + 6 * n:]
        if n and n != len(parts):
            raise SystemExit(f"{lpc}: {n} parts, the text has {len(parts)}: run tools/story_make.py again")
        while len(offs) < len(parts):             # no speech yet: silent parts
            offs.append(0)
            cnts.append(0)
        lines.append(f"static const uint8_t STORY{si}_FRAMES[{max(1, len(frames))}] = {{")
        for i in range(0, len(frames), 24):
            lines.append("    " + ", ".join(str(b) for b in frames[i:i + 24]) + ",")
        if not frames:
            lines.append("    0,")
        lines.append("};")
        lines.append(f"static const uint32_t STORY{si}_OFF[{len(parts)}] = {{{', '.join(map(str, offs))}}};")
        lines.append(f"static const uint16_t STORY{si}_N[{len(parts)}] = {{{', '.join(map(str, cnts))}}};")
        lines.append(f"static const uint8_t STORY{si}_SCENE[{len(parts)}] = {{{', '.join(str(p[0]) for p in parts)}}};")
        lines.append(f"static const char *const STORY{si}_TXT[{len(parts)}] = {{")
        for p in parts:
            lines.append(f"    {cstr(p[1])},")
        lines.append("};")
        table.append(f"    {{STORY{si}_FRAMES, STORY{si}_OFF, STORY{si}_N, STORY{si}_SCENE, STORY{si}_TXT, {len(parts)}}},")
    lines += ["typedef struct { const uint8_t *fr; const uint32_t *off; const uint16_t *n; const uint8_t *scene; const char *const *txt; uint8_t parts; } story_t;",
              "static const story_t STORIES[NSTORY] = {"] + table + ["};", ""]
    Path(out).parent.mkdir(parents=True, exist_ok=True)
    Path(out).write_text("\n".join(lines))
    print(f"stories: {out}")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else str(ROOT / "build" / "gen" / "story_data.h"))
